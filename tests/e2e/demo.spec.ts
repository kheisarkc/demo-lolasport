import { expect, test } from '@playwright/test';
import { chooseSlot, confirmBooking, currentBookingId, futureDay, getApi, login, logout, money, monitor, noOverflow, password, screenshot, uploadProof } from './helpers';

test('customer DP → staff verification → settlement → owner receipts', async ({ page }, testInfo) => {
  const errors = monitor(page);
  await login(page, 'pemilik');
  await expect(page.getByTestId('report-total')).toBeVisible();
  const baseline = money(await page.getByTestId('report-total').innerText());
  await logout(page);
  await chooseSlot(page, testInfo.project.name.includes('mobile') ? 12 : 11);
  const intent = new URL(page.url()).search;
  await screenshot(page, testInfo, 'catalog-booking');
  const bar = await page.getByRole('complementary', { name: 'Ringkasan pilihan' }).boundingBox();
  expect(bar!.y + bar!.height).toBeLessThanOrEqual(page.viewportSize()!.height);
  await page.getByRole('link', { name: 'Lanjutkan', exact: true }).click();
  await expect(page).toHaveURL(/\/masuk\?next=/);
  await page.getByLabel('Email', { exact: true }).fill('pelanggan@lola.test');
  await page.getByLabel('Kata sandi', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Masuk', exact: true }).click();
  await expect(page).toHaveURL(/\/checkout/);
  const intentParams = new URLSearchParams(intent);
  for (const key of ['court', 'hour', 'duration']) expect(new URL(page.url()).searchParams.get(key)).toBe(intentParams.get(key));
  await page.reload();
  await expect(page.getByRole('button', { name: 'Konfirmasi reservasi', exact: true })).toBeDisabled();
  const id = await confirmBooking(page);
  await expect(page.getByText('Status reservasi', { exact: true })).toBeVisible();
  await expect(page.getByText('Status pembayaran', { exact: true })).toBeVisible();
  await expect(page.getByText(/Acuan waktu server/)).toBeVisible();
  const exampleDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Unduh bukti fiktif siap unggah (PNG)' }).click();
  expect((await exampleDownload).suggestedFilename()).toBe('bukti-demo.png');
  await uploadProof(page);
  await expect(page.getByTestId('paid-amount')).toHaveText(/^Rp\s*0$/);
  await noOverflow(page); await screenshot(page, testInfo, 'detail-payment');
  await page.reload(); await expect(page.getByRole('heading', { name: 'Menunggu verifikasi', exact: true })).toBeVisible();
  await logout(page); await login(page, 'pegawai');
  await page.goto('/pegawai/verifikasi?q=' + id);
  await page.getByRole('link').filter({ hasText: `#${id}` }).first().click();
  await expect(page).toHaveURL(new RegExp(`/pegawai/verifikasi/${id}`));
  await expect(page.locator('.proof-image')).toBeVisible();
  await page.getByRole('button', { name: /Perbesar bukti/ }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Tutup dialog' }).click();
  await screenshot(page, testInfo, 'staff-verification');
  await page.getByRole('button', { name: 'Setujui pembayaran', exact: true }).click();
  await page.getByRole('button', { name: 'Ya, setujui pembayaran', exact: true }).click();
  await expect(page.getByText('Pembayaran disetujui dan tercatat.', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Kembali ke antrean' }).click();
  await expect(page).toHaveURL(new RegExp(`q=${id}`));
  await expect(page.getByRole('heading', { name: 'Antrean sudah bersih' })).toBeVisible();
  await logout(page); await login(page, 'pelanggan');
  await page.goto(`/reservasi/${id}`);
  await expect(page.getByRole('heading', { name: 'Lunasi sisa tagihan' })).toBeVisible();
  await page.getByLabel('Metode', { exact: true }).selectOption('qris');
  await uploadProof(page);
  await logout(page); await login(page, 'pegawai'); await page.goto(`/pegawai/verifikasi/${id}`);
  await page.getByRole('button', { name: 'Setujui pembayaran', exact: true }).click();
  await page.getByRole('button', { name: 'Ya, setujui pembayaran', exact: true }).click();
  await expect(page.getByText('Tagihan sudah lunas. Jadwal Anda terkonfirmasi.', { exact: true })).toBeVisible();
  await logout(page); await login(page, 'pemilik');
  await expect(page.getByTestId('report-total')).toBeVisible();
  expect(money(await page.getByTestId('report-total').innerText()) - baseline).toBe(150000);
  const breakdown = await Promise.all(['dp', 'settlement', 'full'].map(k => page.getByTestId(`report-${k}`).innerText()));
  expect(breakdown.reduce((sum, value) => sum + money(value), 0)).toBe(money(await page.getByTestId('report-total').innerText()));
  await page.getByRole('button', { name: 'Hari ini', exact: true }).click();
  await expect(page.getByTestId('report-total')).toBeVisible();
  const data = await (await getApi(page, '/api/v1/reports?from=' + futureDay(0) + '&to=' + futureDay(0))).json();
  expect(money(await page.getByTestId('report-total').innerText())).toBe(data.total);
  expect(data.transactions.filter((p: { booking: { id: number } }) => p.booking.id === Number(id))).toHaveLength(2);
  await noOverflow(page); await screenshot(page, testInfo, 'owner-report');
  expect(errors).toEqual([]);
});

test('registration keeps customer role, session logout and CSRF are enforced over HTTP', async ({ page, request }, testInfo) => {
  const origin = String(testInfo.project.use.baseURL);
  const missing = await request.post('/api/v1/login', { headers: { Origin: origin, Accept: 'application/json' }, data: { email: 'pelanggan@lola.test', password } });
  expect(missing.status()).toBe(419);
  await page.goto('/daftar');
  await page.getByLabel('Nama fiktif').fill('Pelanggan Tes Fiktif');
  await page.getByLabel('Email', { exact: true }).fill(`demo-${Date.now()}-${testInfo.project.name}@example.test`);
  await page.getByLabel('Kata sandi', { exact: true }).fill(password);
  await page.getByLabel('Ulangi kata sandi').fill(password);
  await page.getByRole('button', { name: 'Buat akun', exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.reload(); await page.goto('/reservasi');
  await expect(page.getByRole('heading', { name: 'Belum ada jadwal mendatang' })).toBeVisible();
  const me = await (await getApi(page, '/api/v1/me')).json(); expect(me.role).toBe('customer');
  await logout(page);
  expect((await page.request.get('/api/v1/me', { headers: { Origin: origin, Accept: 'application/json' } })).status()).toBe(401);
});

